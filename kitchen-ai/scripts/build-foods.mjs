// Turns supabase/seed-data/foods.csv into:
//   1) supabase/migrations/20261117000002_seed_foods.sql  (loads the nutrition table into the database)
//   2) supabase/functions/_shared/foods.generated.ts       (same data, used by automated tests)
// Also sanity-checks every row: calories should be close to 4*protein + 4*carbs + 9*fat.
// Run:  node scripts/build-foods.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const csv = readFileSync(new URL('../supabase/seed-data/foods.csv', import.meta.url), 'utf8').trim().split('\n');
const header = csv.shift().split('|');
const rows = csv.map((line) => {
  const c = line.split('|');
  if (c.length !== header.length) throw new Error(`Bad row: ${line}`);
  const [name, aliases, category, kcal, protein, carbs, fat, fiber, tags, safety, source] = c;
  return {
    name: name.trim(),
    aliases: aliases ? aliases.split(';').map((s) => s.trim()).filter(Boolean) : [],
    category,
    kcal: +kcal, protein_g: +protein, carbs_g: +carbs, fat_g: +fat, fiber_g: +fiber,
    tags: tags ? tags.split(',').map((s) => s.trim()) : [],
    safety_class: safety || null,
    source,
  };
});

const SAFETY = new Set(['poultry', 'ground_meat', 'whole_meat', 'fish', 'egg', null]);
const warnings = [];
const names = new Set();
for (const r of rows) {
  if (names.has(r.name)) throw new Error(`Duplicate food: ${r.name}`);
  names.add(r.name);
  if (!SAFETY.has(r.safety_class)) throw new Error(`Bad safety class on ${r.name}`);
  for (const k of ['kcal', 'protein_g', 'carbs_g', 'fat_g', 'fiber_g']) if (!Number.isFinite(r[k])) throw new Error(`Bad number ${k} on ${r.name}`);
  const est = 4 * r.protein_g + 4 * Math.max(0, r.carbs_g - r.fiber_g) + 2 * r.fiber_g + 9 * r.fat_g; // USDA carbs include fiber (~2 kcal/g)
  // fiber, alcohol and rounding cause some drift; flag big gaps only
  if (r.kcal > 30 && Math.abs(est - r.kcal) / r.kcal > 0.25) warnings.push(`${r.name}: listed ${r.kcal} kcal vs ${Math.round(est)} from macros`);
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => (a.length ? `array[${a.map(q).join(',')}]` : `'{}'::text[]`);
const values = rows
  .map((r) => `(${q(r.name)},${arr(r.aliases)},${q(r.category)},${r.kcal},${r.protein_g},${r.carbs_g},${r.fat_g},${r.fiber_g},${arr(r.tags)},${r.safety_class ? q(r.safety_class) : 'null'},${q(r.source)})`)
  .join(',\n');

writeFileSync(
  new URL('../supabase/migrations/20261117000002_seed_foods.sql', import.meta.url),
  `-- GENERATED by scripts/build-foods.mjs from supabase/seed-data/foods.csv. Edit the CSV, not this file.
-- Nutrition values are per 100 g.
insert into public.foods (name, aliases, category, kcal, protein_g, carbs_g, fat_g, fiber_g, tags, safety_class, source) values
${values}
on conflict (name) do update set
  aliases = excluded.aliases, category = excluded.category, kcal = excluded.kcal, protein_g = excluded.protein_g,
  carbs_g = excluded.carbs_g, fat_g = excluded.fat_g, fiber_g = excluded.fiber_g, tags = excluded.tags,
  safety_class = excluded.safety_class, source = excluded.source;
`,
);

writeFileSync(
  new URL('../supabase/functions/_shared/foods.generated.ts', import.meta.url),
  `// GENERATED by scripts/build-foods.mjs — used by automated tests only. The live app reads the database.\nimport type { Food } from './types.ts';\nexport const FOODS: Food[] = ${JSON.stringify(rows.map((r, i) => ({ id: i + 1, ...r })))};\n`,
);

console.log(`${rows.length} foods written.`);
if (warnings.length) console.log('Check these rows:\n  ' + warnings.join('\n  '));
