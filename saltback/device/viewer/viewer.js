/* Saltback drain node viewer. Shows device/out/saltback-node.glb (the same file people download) and the part list
   from device/out/parts.json. Both are generated by device/cad/saltback_node.py; nothing here is drawn by hand. */
import * as THREE from 'three';
import { OrbitControls } from 'three/addons/controls/OrbitControls.js';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { RoomEnvironment } from 'three/addons/environments/RoomEnvironment.js';
import { GLB } from './node-glb.js';
import { NODE } from './parts.js';

const PAGE_URL = 'https://claude.ai/artifact/83HRbmsx6TSDZJ3TNaD3Jd';   // so "Copy link" gives the claude.ai address
const GH_TREE = 'https://github.com/pingusbot67-wq/diamond-challenge-stuff/tree/claude/clever-fermi-0by41q/saltback/device/out';
const $ = id => document.getElementById(id);
const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const reduceMotion = matchMedia('(prefers-reduced-motion: reduce)').matches;
const PARTS = NODE.parts, byPn = Object.fromEntries(PARTS.map(p => [p.pn, p]));
const pnOfNode = name => (byPn[name] ? name : byPn[name.replace(/-\d+$/, '')] ? name.replace(/-\d+$/, '') : null);
let toastT;
const toast = t => { const el = $('toast'); el.textContent = t; el.hidden = false; clearTimeout(toastT); toastT = setTimeout(() => { el.hidden = true; }, 2200); };

/* ---------------- panel ---------------- */
const printed = PARTS.filter(p => p.printed), gPrinted = printed.reduce((a, p) => a + (p.mass_g || 0), 0);
$('facts').innerHTML = [['Part numbers', PARTS.length], [`Printed · ${Math.round(gPrinted)} g`, printed.length], ['Parts cost', `≈ $${NODE.total_usd}`]]
  .map(([k, v]) => `<div><div class="k">${k}</div><div class="v">${v}</div></div>`).join('');
$('files').innerHTML = `<a class="chip solid" href="${esc(NODE.assembly.step)}" target="_blank" rel="noopener">Assembly <span class="ext">STEP</span></a>
  <a class="chip" href="${esc(NODE.assembly.glb)}" target="_blank" rel="noopener">Assembly <span class="ext">GLB</span></a>
  <a class="chip" href="${GH_TREE}" target="_blank" rel="noopener">Every part <span class="ext">STEP · STL</span></a>`;
const tagOf = p => (p.printed ? 'print' : p.kind === 'Purchased' ? 'buy' : 'make');
function renderGroups() {
  $('groups').innerHTML = Object.entries(NODE.subassemblies).map(([sub, name]) => {
    const ps = PARTS.filter(p => p.sub === sub), cost = ps.reduce((a, p) => a + p.usd, 0);
    return `<section class="group"><h3><span>${esc(name)}</span><span class="mono">${sub} · $${cost}</span></h3>${ps.map(p =>
      `<button class="row" type="button" data-pn="${p.pn}" aria-current="${p.pn === sel}"><span class="sw" style="background:${p.color}"></span><span class="pn">${p.pn}</span>
        <span class="nm">${esc(p.name)}${p.qty > 1 ? ` <span class="mono" style="color:var(--muted)">×${p.qty}</span>` : ''}</span><span class="tag ${p.printed ? 'p' : ''}">${tagOf(p)}</span></button>`).join('')}</section>`;
  }).join('');
}
function renderCard() {
  const p = byPn[sel];
  if (!p) { $('card').innerHTML = ''; return; }
  const size = p.size_mm.map(v => v.toFixed(v < 10 ? 1 : 0)).join(' × ');
  $('card').innerHTML = `<article class="card"><div class="top"><button class="close" type="button" id="cClose" aria-label="Close">×</button>
      <div class="pn">${p.pn} · ${esc(p.subName)}</div><h2>${esc(p.name)}</h2>${p.note ? `<p class="note">${esc(p.note)}</p>` : ''}</div>
    <dl><dt>Made by</dt><dd>${esc(p.kind)}</dd><dt>Material</dt><dd>${esc(p.material)}</dd><dt>Size</dt><dd class="mono">${size} mm</dd>
      <dt>Volume</dt><dd class="mono">${p.volume_cm3} cm³${p.mass_g ? ` · ${p.mass_g} g` : ''}</dd><dt>Quantity</dt><dd class="mono">${p.qty}</dd>
      <dt>Cost</dt><dd class="mono">${p.usd ? `≈ $${p.usd}${p.qty > 1 ? ' for all' : ''}` : 'included'}</dd></dl>
    <div class="acts">${p.buy ? `<a class="chip solid" href="${esc(p.buy)}" target="_blank" rel="noopener">Buy</a>` : ''}
      <a class="chip" href="${esc(p.files.step)}" target="_blank" rel="noopener">${p.pn} <span class="ext">STEP</span></a>
      <a class="chip" href="${esc(p.files.stl)}" target="_blank" rel="noopener">${p.pn} <span class="ext">STL</span></a>
      <button class="chip" type="button" id="cCopy">Copy link</button></div></article>`;
  $('cClose').onclick = () => select(null);
  $('cCopy').onclick = async () => { const url = `${PAGE_URL || location.href.split('#')[0]}#${p.pn.toLowerCase()}`;
    try { await navigator.clipboard.writeText(url); toast('Link copied'); } catch { toast(url); } };
}
$('groups').addEventListener('click', e => { const b = e.target.closest('[data-pn]'); if (b) select(b.dataset.pn === sel ? null : b.dataset.pn, true); });

/* ---------------- 3D ---------------- */
const stage = $('stage');
const renderer = new THREE.WebGLRenderer({ antialias: true, alpha: true });
renderer.setPixelRatio(Math.min(2, devicePixelRatio || 1));
renderer.toneMapping = THREE.ACESFilmicToneMapping; renderer.toneMappingExposure = 1.05;
renderer.shadowMap.enabled = true; renderer.shadowMap.type = THREE.PCFSoftShadowMap; renderer.localClippingEnabled = true;
stage.prepend(renderer.domElement);
const scene = new THREE.Scene();
scene.environment = new THREE.PMREMGenerator(renderer).fromScene(new RoomEnvironment(renderer), 0.04).texture;
const camera = new THREE.PerspectiveCamera(32, 1, 0.005, 20); camera.layers.enable(1);   // layer 1: edge lines (drawn, not picked)
const controls = new OrbitControls(camera, renderer.domElement); controls.enableDamping = true; controls.dampingFactor = 0.08; controls.screenSpacePanning = true;
const sun = new THREE.DirectionalLight(0xffffff, 1.4); sun.position.set(0.7, 1.4, 0.9); sun.castShadow = true;
Object.assign(sun.shadow.camera, { left: -0.5, right: 0.5, top: 0.5, bottom: -0.5, near: 0.1, far: 4 }); sun.shadow.mapSize.set(2048, 2048); sun.shadow.bias = -0.0004;
scene.add(sun, new THREE.HemisphereLight(0xffffff, 0x8a8f94, 0.35));
const ground = new THREE.Mesh(new THREE.PlaneGeometry(6, 6), new THREE.ShadowMaterial({ opacity: 0.13 }));
ground.rotation.x = -Math.PI / 2; ground.receiveShadow = true; scene.add(ground);
const section = new THREE.Plane(new THREE.Vector3(-1, 0, 0), 0);
const lineMat = new THREE.LineBasicMaterial({ transparent: true, opacity: 0.22, depthWrite: false });
const css = k => getComputedStyle(document.documentElement).getPropertyValue(k).trim();
const accent = new THREE.Color();
function readTheme() { lineMat.color.set(css('--ink')); accent.set(css('--accent')); }
readTheme();
matchMedia('(prefers-color-scheme: dark)').addEventListener('change', readTheme);
new MutationObserver(readTheme).observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] });

const finish = m => /stainless|steel/i.test(m) ? { metalness: 0.85, roughness: 0.32 } : /PCB/.test(m) ? { metalness: 0.15, roughness: 0.5 }
  : /Li-ion/.test(m) ? { metalness: 0.2, roughness: 0.38 } : /PVC/.test(m) ? { metalness: 0, roughness: 0.48 } : { metalness: 0, roughness: 0.62 };
const objs = {};   // pn -> [{ obj, home, meshes }]
let root, whole = new THREE.Box3(), explode = 0, explodeTo = 0, sel = null, hover = null, xray = false, sectionOn = false, isolate = false;

function load() {
  const bin = atob(GLB), buf = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) buf[i] = bin.charCodeAt(i);
  new GLTFLoader().parse(buf.buffer, '', gltf => {
    root = gltf.scene; scene.add(root);
    root.traverse(o => {
      const pn = o.name && pnOfNode(o.name); if (!pn || o.parent?.name && pnOfNode(o.parent.name)) return;
      const meta = byPn[pn], meshes = [];
      o.traverse(m => { if (!m.isMesh) return;
        m.material = new THREE.MeshStandardMaterial({ color: meta.color, ...finish(meta.material), polygonOffset: true, polygonOffsetFactor: 1, polygonOffsetUnits: 1, side: THREE.DoubleSide });
        m.castShadow = m.receiveShadow = true; m.userData.pn = pn; meshes.push(m);
        if (!['SB-407', 'SB-504'].includes(pn) && m.geometry.index && m.geometry.index.count / 3 < 25000) { const l = new THREE.LineSegments(new THREE.EdgesGeometry(m.geometry, 30), lineMat); l.layers.set(1); m.add(l); } });
      (objs[pn] = objs[pn] || []).push({ obj: o, home: o.position.clone(), meshes });
    });
    root.updateMatrixWorld(true); whole.setFromObject(root);
    ground.position.y = whole.min.y - 0.001;
    $('loading').remove(); resize(); frame(whole, false, 1.0); fromHash();
  }, err => { $('loading').textContent = `The model could not load: ${err.message || err}`; });
}

function frame(box, animate = true, pad = 1.15, dir = new THREE.Vector3(0.62, 0.38, 1).normalize()) {
  const c = box.getCenter(new THREE.Vector3()), s = box.getSize(new THREE.Vector3());
  const fitH = s.y / 2 / Math.tan(THREE.MathUtils.degToRad(camera.fov / 2)), fitW = Math.max(s.x, s.z) / 2 / Math.tan(THREE.MathUtils.degToRad(camera.fov / 2)) / camera.aspect;
  const dist = Math.max(fitH, fitW, 0.08) * pad + Math.max(s.x, s.z) / 2;
  fly = { t: animate && !reduceMotion ? 0 : 1, fromT: controls.target.clone(), fromP: camera.position.clone(), toT: c, toP: c.clone().addScaledVector(dir, dist) };
  if (fly.t === 1) { controls.target.copy(c); camera.position.copy(fly.toP); }
}
let fly = null;

function paint() {
  for (const [pn, list] of Object.entries(objs)) for (const { obj, meshes } of list) {
    const housing = ['SB-101', 'SB-102', 'SB-103'].includes(pn), on = pn === sel, hov = pn === hover;
    obj.visible = !isolate || !sel || on;
    for (const m of meshes) {
      const see = xray && housing && !on;
      Object.assign(m.material, { transparent: see, opacity: see ? 0.16 : 1, depthWrite: !see });
      m.material.emissive.copy(on ? accent : hov ? accent : new THREE.Color(0)); m.material.emissiveIntensity = on ? 0.28 : hov ? 0.12 : 0;
      m.material.clippingPlanes = sectionOn ? [section] : [];
      m.children.forEach(l => { l.visible = !see; });
    }
  }
  lineMat.clippingPlanes = sectionOn ? [section] : [];
}

function partBox(pn) { const b = new THREE.Box3(); (objs[pn] || []).forEach(({ obj }) => b.expandByObject(obj)); return b; }
function select(pn, fromList = false) {
  sel = pn && byPn[pn] ? pn : null;
  renderGroups(); renderCard(); paint();
  const h = sel ? `#${sel.toLowerCase()}` : ' ';
  try { history.replaceState(null, '', sel ? h : location.pathname + location.search); } catch {}
  if (sel && root) { const b = partBox(sel), s = b.getSize(new THREE.Vector3()).length();
    frame(isolate ? b : b.clone().expandByScalar(Math.max(0.06, s * 0.8)), true, isolate ? 1.8 : 1.25); }
  if (sel && fromList && matchMedia('(max-width: 900px)').matches) stage.scrollIntoView({ behavior: reduceMotion ? 'auto' : 'smooth' });
}
function fromHash() { const id = location.hash.slice(1).toUpperCase(); if (byPn[id]) select(id); else { renderGroups(); renderCard(); paint(); } }
window.addEventListener('hashchange', fromHash);

/* dock */
document.querySelectorAll('[data-mode]').forEach(b => b.addEventListener('click', () => {
  explodeTo = b.dataset.mode === 'exploded' ? 1 : 0;
  document.querySelectorAll('[data-mode]').forEach(x => x.setAttribute('aria-pressed', String(x === b)));
  if (root) frame(explodeTo ? whole.clone().expandByScalar(0.09) : whole, true, 1.0);
}));
const toggle = (id, fn) => $(id).addEventListener('click', e => { const on = e.currentTarget.getAttribute('aria-pressed') !== 'true'; e.currentTarget.setAttribute('aria-pressed', String(on)); fn(on); paint(); });
toggle('bSection', on => { sectionOn = on; if (on && root) frame(partBox('SB-101').expandByScalar(0.06), true, 1.1, new THREE.Vector3(1, 0.35, 0.25).normalize()); });
toggle('bXray', on => { xray = on; });
toggle('bIsolate', on => { isolate = on; if (on && !sel) toast('Pick a part to isolate'); if (sel) select(sel); });
$('bReset').addEventListener('click', () => { if (root) frame(whole, true, 1.0); });

/* hover and click */
const ray = new THREE.Raycaster(), ptr = new THREE.Vector2(), tip = $('tip');
function pick(e) {
  const r = renderer.domElement.getBoundingClientRect(); ptr.set((e.clientX - r.left) / r.width * 2 - 1, -(e.clientY - r.top) / r.height * 2 + 1);
  ray.setFromCamera(ptr, camera);
  const hit = root && ray.intersectObject(root, true).find(h => h.object.isMesh && h.object.visible && h.object.material.opacity > 0.5 && (!sectionOn || h.point.x <= 0.0005));
  return hit ? hit.object.userData.pn : null;
}
renderer.domElement.addEventListener('pointermove', e => {
  if (e.buttons) return;
  const pn = pick(e); if (pn !== hover) { hover = pn; paint(); }
  renderer.domElement.style.cursor = pn ? 'pointer' : '';
  if (pn) { const r = stage.getBoundingClientRect(); tip.innerHTML = `<span class="mono">${pn}</span>${esc(byPn[pn].name)}`; tip.hidden = false;
    tip.style.left = `${e.clientX - r.left}px`; tip.style.top = `${e.clientY - r.top}px`; } else tip.hidden = true;
});
renderer.domElement.addEventListener('pointerleave', () => { hover = null; tip.hidden = true; paint(); });
let down = null;
renderer.domElement.addEventListener('pointerdown', e => { down = [e.clientX, e.clientY]; });
renderer.domElement.addEventListener('pointerup', e => { if (!down || Math.hypot(e.clientX - down[0], e.clientY - down[1]) > 5) return; const pn = pick(e); select(pn === sel ? null : pn); });

function resize() { const w = stage.clientWidth, h = stage.clientHeight; renderer.setSize(w, h, false); camera.aspect = w / h; camera.updateProjectionMatrix(); }
new ResizeObserver(resize).observe(stage);
const clock = new THREE.Clock();
function loop() {
  requestAnimationFrame(loop);
  const dt = Math.min(0.05, clock.getDelta());
  if (Math.abs(explode - explodeTo) > 1e-4) {
    explode += (explodeTo - explode) * Math.min(1, dt * (reduceMotion ? 60 : 5));
    for (const [pn, list] of Object.entries(objs)) { const v = byPn[pn].explode;
      list.forEach(({ obj, home }) => { obj.position.set(home.x + v[0] * explode, home.y + v[1] * explode, home.z + v[2] * explode); });
      if (pn === 'SB-407' || pn === 'SB-504') list.forEach(({ obj }) => { obj.visible = explode < 0.25 && (!isolate || !sel || sel === pn); }); }
  }
  if (fly && fly.t < 1) { fly.t = Math.min(1, fly.t + dt * 1.6); const k = 1 - (1 - fly.t) ** 3;
    controls.target.lerpVectors(fly.fromT, fly.toT, k); camera.position.lerpVectors(fly.fromP, fly.toP, k); }
  controls.update(); renderer.render(scene, camera);
}
renderGroups();
load(); loop();
